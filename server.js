/* ==========================================
   API
========================================== */

app.post("/api/continue", async (req, res) => {

    try {

        const text = String(
            req.body?.text || ""
        ).trim();

        const topic = String(
            req.body?.topic || "Без темы"
        );


        /* ==================================
           ПРОВЕРКИ
        ================================== */

        if (!text) {

            return res.status(400).json({
                error: "Введите начало текста."
            });

        }


        if (text.length > 3000) {

            return res.status(400).json({
                error:
                    "Максимальная длина текста — 3000 символов."
            });

        }


        /* ==================================
           ФИЛЬТР
        ================================== */

        if (checkBlocked(text)) {

            return res.status(400).json({

                blocked: true,

                message:
`NeuroProda не может продолжить данный текст.

Причина: введённый запрос содержит тему или содержание, которое не поддерживается данным сервисом.

NeuroProda предназначена для создания безопасных рассказов, историй, шуток, игровых идей, фантастики, мемов и других нейтральных материалов.

Пожалуйста, измените начало текста и попробуйте снова.

Спасибо за понимание.`

            });

        }


        /* ==================================
           ТЕМА
        ================================== */

        const topicRule =
            topicInstructions[topic] ||
            topicInstructions["Без темы"];


        /* ==================================
           GROQ
        ================================== */

        const response =
            await client.responses.create({

                model: "openai/gpt-oss-20b",

                instructions: `
Ты — NeuroProda, многоязычная нейросеть для продолжения текста.

ОПРЕДЕЛЕНИЕ ЯЗЫКА:

Сначала определи язык, на котором написана основная часть пользовательского текста.

Затем ВСЕГДА продолжай текст на этом же языке.

Примеры:

Русский:
"Мишка бегал по лужайке"
→ продолжение на русском.

English:
"The bear was running across the meadow"
→ continuation in English.

Українська:
"Ведмедик біг по галявині"
→ продовження українською.

Deutsch:
"Der Bär lief über die Wiese"
→ Fortsetzung auf Deutsch.

Español:
"El oso corría por el prado"
→ continuación en español.

Polski:
"Miś biegł po polanie"
→ kontynuacja po polsku.

Français:
"L'ours courait dans la prairie"
→ continuation en français.

ПРАВИЛА:

1. Не переводи исходный текст.
2. Не меняй язык без необходимости.
3. Не пересказывай начало.
4. Сразу продолжай историю.
5. Напиши примерно 5–8 абзацев.
6. Делай каждый ответ новым.
7. Не используй заранее заготовленные тексты.
8. Сохраняй стиль исходного текста.
9. Сохраняй персонажей и события.
10. Не начинай с "Вот продолжение".
11. Не добавляй служебные комментарии.
12. Если пользователь смешивает несколько языков, используй язык, который преобладает в основном тексте.
13. Если текст очень короткий, определи язык по доступным словам и продолжи на нём.
14. Сохраняй выбранную тему.

ВЫБРАННАЯ ТЕМА:
${topic}

СТИЛЬ ТЕМЫ:
${topicRule}
`,

                input: text

            });


        /* ==================================
           РЕЗУЛЬТАТ
        ================================== */

        const generatedText =
            response.output_text;


        if (!generatedText) {

            return res.status(500).json({
                error:
                    "NeuroProda не получила текст от нейросети."
            });

        }


        res.json({
            text: generatedText
        });

    }


    catch (error) {

        console.error("");
        console.error("========== GROQ ERROR ==========");
        console.error(error);
        console.error("================================");
        console.error("");

        res.status(500).json({

            error:
                error?.message ||
                "Ошибка Groq API."

        });

    }

});


